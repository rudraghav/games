'use client';
import { useState } from 'react';
import { mapRoom } from '@games/api-client/mappers';
import { tableRegistry } from '@/games/registry';
import { fixtures } from '@/stories/generated/rooms';
export function DesignGallery() {
  const [index, setIndex] = useState(0);
  const [pending, setPending] = useState(false);
  const [disconnected, setDisconnected] = useState(false);
  const fixture = fixtures[index];
  const room = mapRoom(fixture.room);
  const Table = tableRegistry[room.gameId];
  return (
    <main className="page-width" style={{ paddingTop: 30, paddingBottom: 60 }}>
      <h1 className="heading-md">The component room.</h1>
      <p className="small muted" style={{ margin: '12px 0 24px' }}>
        Synthetic preview scenarios generated by the game engines.
      </p>
      <label className="field">
        Table scenario
        <select
          className="input"
          value={index}
          onChange={(event) => setIndex(Number(event.target.value))}
        >
          {fixtures.map((fixture, i) => (
            <option key={i} value={i}>
              {fixture.label}
            </option>
          ))}
        </select>
      </label>
      <div style={{ display: 'flex', gap: 20, margin: '20px 0' }}>
        <label>
          <input
            type="checkbox"
            checked={pending}
            onChange={(event) => setPending(event.target.checked)}
          />{' '}
          Saving a move
        </label>
        <label>
          <input
            type="checkbox"
            checked={disconnected}
            onChange={(event) => setDisconnected(event.target.checked)}
          />{' '}
          Disconnected
        </label>
      </div>
      {room.game ? (
        <Table
          key={index}
          room={{ ...room, paused: disconnected }}
          match={room.game}
          selfId={fixture.selfId}
          onAction={() => undefined}
          pending={pending}
        />
      ) : null}
    </main>
  );
}
